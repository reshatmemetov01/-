# Скидка, которую получает пользователь из дожимающей цепочки
DISCOUNT_PERCENT = 20
DISCOUNT_DURATION = timedelta(hours=48)


def discounted(price: int, active: bool) -> int:
    if not active:
        return price
    return round(price * (100 - DISCOUNT_PERCENT) / 100 / 10) * 10


def tariffs_text(discount_active: bool) -> str:
    lines = []
    for t in TARIFFS:
        price = discounted(t.price, discount_active)
        price_str = (
            f"<s>{t.price} ₽</s> <b>{price} ₽</b>" if discount_active else f"<b>{price} ₽</b>"
        )
        lines.append(f"▪️ <b>{t.title}</b> — {price_str}\n{t.description}")
    text = "\n\n".join(lines)
    if discount_active:
        text = f"🔥 Для вас действует скидка {DISCOUNT_PERCENT}%!\n\n" + text
    return text


