# Сколько ошибок допустимо на реальном экзамене (20 вопросов) — используется в текстах.
EXAM_MAX_ERRORS = 2


def quiz_result_text(correct: int, total: int) -> str:
    wrong = total - correct
    head = f"📊 <b>Ваш результат: {correct} из {total}</b>\n\n"
    if wrong == 0:
        verdict = (
            "Отлично! 🔥 Но в реальном экзамене 20 вопросов, а в базе — 800. "
            "Чтобы сдать гарантированно, нужно уверенно знать все темы, "
            "а не только самые частые."
        )
    elif wrong <= 1:
        verdict = (
            "Хороший уровень! Но на 20 вопросах это уже ~2 ошибки — ровно на грани "
            f"(допускается не больше {EXAM_MAX_ERRORS}). Одна случайная ошибка — и пересдача."
        )
    elif wrong <= 3:
        verdict = (
            f"Если перенести на экзамен — это {wrong * 2} ошибок из 20. "
            f"А допускается не больше {EXAM_MAX_ERRORS}. "
            "Сейчас экзамен был бы <b>не сдан</b> 😕"
        )
    else:
        verdict = (
            f"Пока {wrong} ошибок из {total}. С таким результатом экзамен в ГИБДД "
            "не сдать — но это легко исправить системной подготовкой."
        )
    return head + verdict


